
enum SyncPhase {
  /// Совместного прослушивания нет.
  idle,

  /// Сессия есть, но звук сейчас не идёт: пауза или очередь не запущена.
  waiting,

  /// Играет одно и то же в одну и ту же секунду.
  synced,

  /// Идёт подстройка: трек готовится, сервер скомандовал перемотку,
  /// выполняется автопереход.
  drifting,
}